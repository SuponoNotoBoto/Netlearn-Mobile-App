import 'dart:math' as math;

import 'package:ar_flutter_plugin_plus/datatypes/node_types.dart';
import 'package:ar_flutter_plugin_plus/models/ar_node.dart';
import 'package:flutter/widgets.dart' show Matrix4;

import 'ar_lab_layout.dart';
import 'ar_marker_catalog.dart' show kArAndroidModelScaleFactor;

/// Builds the Modul 4 (marker 6) interactive AR lab from a single assembled
/// model, plus a packet node the scanner animates along the cables.
///
/// The whole lab — two computers, one switch and the two connecting cables — is
/// one GLB (`assets/3D/2pc1switch.glb`, re-exported by the user, optimized by
/// `tool/prepare_lab_models.py` into `optimized/lab_full.glb`). An earlier
/// version assembled the lab from separate per-device nodes, which did not read
/// as one object on device. The plugin (`ar_flutter_plugin_plus`) exposes no
/// animation playback and cannot address nodes inside a loaded GLB, so the only
/// thing that moves is the packet: a separate small node the scanner repositions
/// every frame.
///
/// This file is deliberately free of Flutter widgets, the AR session and
/// Supabase. It only produces [ARNode]s and `Matrix4` values from the marker
/// pose, so the whole scene geometry — scaling, cabling and the packet path — is
/// unit tested offline without a camera. The scanner owns adding/removing the
/// nodes and driving the packet animation.
///
/// Geometry lives in [ar_lab_layout.dart], which `tool/prepare_lab_models.py`
/// regenerates from the GLB itself (the lab's bounds, the two computer centres
/// and the ordered cable centreline). Editing that file by hand is pointless —
/// re-run the tool after re-exporting the model instead.
///
/// The plugin's native renderer multiplies every node matrix by
/// `androidModelScaleFactor` (0.33) in local space (`AndroidARView.kt`), which
/// scales the node's linear part but not its translation column. Node matrices
/// are therefore composed as `markerPose * T(localOffset) * R * S`, and the
/// scale below is divided by [kArAndroidModelScaleFactor] to reach the intended
/// real-world size.

/// Largest dimension the assembled lab should occupy on device, in metres. The
/// marker card is assumed ~0.20 m wide; the lab is much wider than deep, so this
/// sets its long (X) side and the computers come out ~10 cm tall.
const double kArLabSceneTargetWidth = 0.34;

/// Edge length of the animated data packet, in metres.
const double kArLabPacketSize = 0.03;

/// Distance a tap may land from a computer centre and still select it, in
/// metres. The two computers sit ~0.24 m apart in the assembled lab, so a value
/// below half that stays unambiguous.
const double kArLabTapThreshold = 0.11;

/// Orientation tuning knobs (degrees). Which way the assembled model faces the
/// camera cannot be told from the console, so these default to 0 and exist to
/// stand the lab up or spin it in a single on-device pass if it reads wrong.
const double kArLabSceneYawDegrees = 0.0;
const double kArLabScenePitchDegrees = 0.0;

/// GLB asset paths. The lab is the user's assembled model, optimized by
/// `tool/prepare_lab_models.py`; the packet is generated by
/// `tool/make_lab_assets.dart`.
const String kArLabSceneAsset = 'assets/3D/modul_4/optimized/lab_full.glb';
const String kArLabPacketAsset = 'assets/3D/lab_packet.glb';

/// Node names. The scanner uses these to add/remove the lab and to drive the
/// packet.
const String kArLabNodeScene = 'ar_lab_full';
const String kArLabNodePacket = 'ar_lab_packet';

/// The two configurable computers. The switch is deliberately not selectable —
/// it has no IP configuration.
enum ArLabDevice { pcA, pcB }

/// Asset-space centre of [device], straight from the generated layout. Kept
/// public (rather than only exposed as a world point) so tests can reason about
/// the lab layout without a marker pose.
List<double> arLabDeviceLocalCenter(ArLabDevice device) => switch (device) {
      ArLabDevice.pcA => kArLabPcALocalCenter,
      ArLabDevice.pcB => kArLabPcBLocalCenter,
    };

/// The single static lab node, anchored to the marker pose. The packet is added
/// separately by [arLabPacketNode] once a test succeeds.
List<ARNode> arLabStaticNodes(Matrix4 markerPose) {
  return <ARNode>[
    ARNode(
      type: NodeType.localGLB,
      uri: kArLabSceneAsset,
      name: kArLabNodeScene,
      transformation: markerPose.clone()..multiply(_labLocalMatrix()),
    ),
  ];
}

/// The packet node, positioned at the start of the path (Computer A).
ARNode arLabPacketNode(String name, Matrix4 markerPose) {
  return ARNode(
    type: NodeType.localGLB,
    uri: kArLabPacketAsset,
    name: name,
    transformation: arLabPacketTransform(markerPose, 0),
  );
}

/// World matrix for the packet at [t] in `0..1` along A -> switch -> B.
Matrix4 arLabPacketTransform(Matrix4 markerPose, double t) {
  final List<double> p = arLabPacketLocalPosition(t);
  final double s = _packetScale();
  return markerPose.clone()
    ..translateByDouble(p[0], p[1], p[2], 1.0)
    ..scaleByDouble(s, s, s, 1.0);
}

/// World matrix for the packet at [t] in `0..1` along Computer A -> switch only.
///
/// A failed connection must never be shown as a packet reaching Computer B
/// (AR_PRD §6.4C, AR-12), so the full A -> switch -> B path is truncated at the
/// switch: at `t = 1` the packet is exactly at the switch, where the drop cable
/// of Computer A meets it, and a loop back to `t = 0` reads as a retry.
Matrix4 arLabPacketToSwitchTransform(Matrix4 markerPose, double t) {
  return arLabPacketTransform(markerPose, t * kArLabPacketToSwitchFraction);
}

/// Portion of one failure-animation loop spent *moving* A -> switch; the rest
/// holds the packet at the switch before the loop restarts, so the failed
/// connection reads as "stopped at the switch, retrying" rather than a steady
/// bounce.
const double kArLabPacketFailureMovePortion = 0.7;

/// Maps the failure loop tick [t] in `0..1` to the progress along the A ->
/// switch leg (also `0..1`, for [arLabPacketToSwitchTransform]).
///
/// For `t < [kArLabPacketFailureMovePortion]` the packet travels; afterwards it
/// stays parked at the switch until the loop restarts.
double arLabPacketFailureProgress(double t) {
  final double clamped = t.clamp(0.0, 1.0);
  return clamped < kArLabPacketFailureMovePortion
      ? clamped / kArLabPacketFailureMovePortion
      : 1.0;
}

/// Marker-local packet position (metres) at [t] in `0..1`.
///
/// Follows the baked cable centreline (Computer A -> switch -> Computer B) with
/// constant arc-length speed, so the packet travels at the same visual pace
/// along both cables rather than faster along the longer one.
List<double> arLabPacketLocalPosition(double t) {
  final double clamped = t.clamp(0.0, 1.0);
  final List<double> point = _pointAlongPath(clamped);
  return _labOffset(point);
}

/// World-space centre of [device] at [markerPose].
List<double> arLabDeviceWorldCenter(ArLabDevice device, Matrix4 markerPose) {
  final List<double> offset = _labOffset(arLabDeviceLocalCenter(device));
  final Matrix4 m = markerPose.clone()
    ..translateByDouble(offset[0], offset[1], offset[2], 1.0);
  final t = m.getTranslation();
  return <double>[t.x, t.y, t.z];
}

/// Nearest configurable computer to a tapped world point, or `null` when the tap
/// is farther than [threshold] from both.
///
/// The plugin cannot report 3D node taps on Android (`onNodeTap` is never sent
/// natively), so selection is done via an ARCore hit-test pose and this nearest
/// -centre match. The scanner also offers labelled buttons as a guaranteed path.
ArLabDevice? arLabDeviceAt(
  List<double> worldPoint,
  Matrix4 markerPose, {
  double threshold = kArLabTapThreshold,
}) {
  ArLabDevice? best;
  double bestDistance = threshold;
  for (final ArLabDevice device in ArLabDevice.values) {
    final List<double> center = arLabDeviceWorldCenter(device, markerPose);
    final double d = _length(
      worldPoint[0] - center[0],
      worldPoint[1] - center[1],
      worldPoint[2] - center[2],
    );
    if (d <= bestDistance) {
      bestDistance = d;
      best = device;
    }
  }
  return best;
}

/// Node scale that renders the packet (authored at extent 1) at
/// [kArLabPacketSize] after the plugin's native 0.33 factor.
double _packetScale() =>
    kArLabPacketSize / (1.0 * kArAndroidModelScaleFactor);

/// The lab's anchor point in asset space: centred in X/Z, resting on its lowest
/// Y. The whole model is shifted so this point sits at the marker origin.
List<double> get _labAnchor => <double>[
      (kArLabBoundsMin[0] + kArLabBoundsMax[0]) / 2,
      kArLabBoundsMin[1],
      (kArLabBoundsMin[2] + kArLabBoundsMax[2]) / 2,
    ];

/// Node scale that renders the lab's native X span at [kArLabSceneTargetWidth]
/// after the plugin's native 0.33 factor.
double get _labScale =>
    kArLabSceneTargetWidth /
    ((kArLabBoundsMax[0] - kArLabBoundsMin[0]) * kArAndroidModelScaleFactor);

/// The [kArAndroidModelScaleFactor] * nodeScale factor actually applied to the
/// lab's linear part on device.
double get _labWorldScale => kArAndroidModelScaleFactor * _labScale;

/// `markerPose * T * R * S` local matrix for the lab node. `T` places the anchor
/// at the marker origin (after rotation), `R` is the orientation knob and `S` is
/// [_labScale].
Matrix4 _labLocalMatrix() {
  final List<double> rotatedAnchor = _rotateVector(_labAnchor);
  final double e = _labWorldScale;
  final Matrix4 local = Matrix4.identity()
    ..translateByDouble(
      -e * rotatedAnchor[0],
      -e * rotatedAnchor[1],
      -e * rotatedAnchor[2],
      1.0,
    )
    ..multiply(_rotationMatrix());
  local.scaleByDouble(_labScale, _labScale, _labScale, 1.0);
  return local;
}

/// Marker-local offset (metres) of an asset-space [point]: the lab transform
/// (scale, orientation, anchor shift) applied without the marker pose.
List<double> _labOffset(List<double> point) {
  final List<double> anchor = _labAnchor;
  final List<double> v = <double>[
    point[0] - anchor[0],
    point[1] - anchor[1],
    point[2] - anchor[2],
  ];
  final List<double> r = _rotateVector(v);
  final double e = _labWorldScale;
  return <double>[e * r[0], e * r[1], e * r[2]];
}

/// Orientation matrix R = Rx(pitch) * Ry(yaw), matching [_rotateVector].
Matrix4 _rotationMatrix() {
  if (kArLabSceneYawDegrees == 0 && kArLabScenePitchDegrees == 0) {
    return Matrix4.identity();
  }
  final double yaw = kArLabSceneYawDegrees * math.pi / 180;
  final double pitch = kArLabScenePitchDegrees * math.pi / 180;
  return Matrix4.rotationX(pitch) * Matrix4.rotationY(yaw);
}

/// Applies R = Rx(pitch) * Ry(yaw) to [v], matching [_rotationMatrix].
List<double> _rotateVector(List<double> v) {
  if (kArLabSceneYawDegrees == 0 && kArLabScenePitchDegrees == 0) {
    return <double>[v[0], v[1], v[2]];
  }
  final double yaw = kArLabSceneYawDegrees * math.pi / 180;
  final double pitch = kArLabScenePitchDegrees * math.pi / 180;
  final double cy = math.cos(yaw);
  final double sy = math.sin(yaw);
  final double cp = math.cos(pitch);
  final double sp = math.sin(pitch);

  // Yaw about Y first...
  final double x1 = cy * v[0] + sy * v[2];
  final double z1 = -sy * v[0] + cy * v[2];
  // ...then pitch about X.
  final double y2 = cp * v[1] - sp * z1;
  final double z2 = sp * v[1] + cp * z1;
  return <double>[x1, y2, z2];
}

/// Cumulative arc lengths (asset space) of [kArLabPacketPathLocal], computed
/// once.
final List<double> _kLabPathCumulative = () {
  final List<double> cumulative = <double>[0];
  for (int i = 1; i < kArLabPacketPathLocal.length; i++) {
    final List<double> a = kArLabPacketPathLocal[i - 1];
    final List<double> b = kArLabPacketPathLocal[i];
    cumulative.add(
      cumulative[i - 1] + _length(b[0] - a[0], b[1] - a[1], b[2] - a[2]),
    );
  }
  return cumulative;
}();

/// Asset-space point at fraction [t] (already clamped) along the packet path.
List<double> _pointAlongPath(double t) {
  final List<double> cumulative = _kLabPathCumulative;
  final double total = cumulative.last;
  if (total <= 0) return kArLabPacketPathLocal.first;
  final double target = t * total;
  for (int i = 1; i < cumulative.length; i++) {
    if (cumulative[i] >= target) {
      final double segment = cumulative[i] - cumulative[i - 1];
      final double local =
          segment <= 0 ? 0 : (target - cumulative[i - 1]) / segment;
      return _lerp(
        kArLabPacketPathLocal[i - 1],
        kArLabPacketPathLocal[i],
        local,
      );
    }
  }
  return kArLabPacketPathLocal.last;
}

List<double> _lerp(List<double> a, List<double> b, double t) => <double>[
      a[0] + (b[0] - a[0]) * t,
      a[1] + (b[1] - a[1]) * t,
      a[2] + (b[2] - a[2]) * t,
    ];

double _length(double x, double y, double z) => math.sqrt(x * x + y * y + z * z);
